def search_relevant_context(query: str, risk_score: float = 0.0) -> str:
    """
    Простой контекстный поиск нормативной базы на основе уровня риска и ключевых слов.
    """
    retrieved_docs = []

    # Если высокий риск (ML > 0.7) или в запросе есть упоминание дробления/интервалов
    if risk_score >= 0.7 or "дроблен" in query.lower() or "интервал" in query.lower():
        retrieved_docs.append(LEGAL_KNOWLEDGE_BASE[0])  # Дробление
        retrieved_docs.append(LEGAL_KNOWLEDGE_BASE[2])  # КоАП 207

    # По умолчанию подключаем общие нормы закупок из одного источника
    retrieved_docs.append(LEGAL_KNOWLEDGE_BASE[1])

    # Формируем итоговый текстовый блок для промпта
    context_text = "\n\n".join(
        [f"--- {doc['title']} ---\n{doc['content']}" for doc in retrieved_docs]
    )
    
    return context_text